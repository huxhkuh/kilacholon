const entryFromRevision = (revision: ApprovedRevision, base?: Entry): Entry => ({
  slug: revision.entry_slug,
  title: revision.title,
  category: revision.category,
  tags: revision.tags ?? [],
  level: base?.level ?? 'מתחילים',
  shortDescription: revision.summary,
  fullDescription: revision.content,
  whyImportant: base?.whyImportant ?? '',
  example: base?.example ?? '',
  pros: base?.pros ?? [],
  cons: base?.cons ?? [],
  faq: base?.faq ?? [],
  related: base?.related ?? [],
  views: base?.views ?? 0,
  updatedAt: revision.reviewed_at ?? revision.created_at,
});

export const mergeApprovedRevisions = (
  baseEntries: Entry[],
  revisions: ApprovedRevision[],
) => {
  const latestBySlug = new Map<string, ApprovedRevision>();
  [...revisions]
    .sort((a, b) => b.created_at.localeCompare(a.created_at))
    .forEach(revision => {
      if (!latestBySlug.has(revision.entry_slug)) {
        latestBySlug.set(revision.entry_slug, revision);
      }
    });

  const merged = baseEntries.map(entry => {
    const revision = latestBySlug.get(entry.slug);
    if (!revision) return entry;
    latestBySlug.delete(entry.slug);
    return entryFromRevision(revision, entry);
  });

  return [
    ...merged,
    ...Array.from(latestBySlug.values()).map(revision => entryFromRevision(revision)),
  ];
};

export const getEntry = (slug: string, sourceEntries = entries) => sourceEntries.find(e => e.slug === slug);
export const getCategory = (slug: string) => categories.find(c => c.slug === slug);
export const getEntriesByCategory = (slug: string, sourceEntries = entries) => sourceEntries.filter(e => e.category === slug);
export const featuredEntries = (sourceEntries = entries) => sourceEntries.slice(0, 6);
export const recentEntries = (sourceEntries = entries) => [...sourceEntries].sort((a, b) => b.updatedAt.localeCompare(a.updatedAt)).slice(0, 6);
export const searchEntries = (q: string, sourceEntries = entries) => {
  const query = q.trim().toLowerCase();
  if (!query) return [];
  return sourceEntries.filter(e =>
    e.title.toLowerCase().includes(query) ||
    e.shortDescription.toLowerCase().includes(query) ||
    e.fullDescription.toLowerCase().includes(query) ||
    e.tags.some(t => t.toLowerCase().includes(query))
  );
};
